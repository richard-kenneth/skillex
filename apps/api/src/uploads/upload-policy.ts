import { randomUUID } from 'node:crypto';

const AVATAR_MIME_EXTENSIONS: ReadonlyMap<string, string> = new Map([
  ['image/jpeg', 'jpg'],
  ['image/png', 'png'],
  ['image/webp', 'webp'],
  ['image/gif', 'gif'],
  ['image/avif', 'avif'],
]);

const ATTACHMENT_MIME_EXTENSIONS: ReadonlyMap<string, string> = new Map([
  ...AVATAR_MIME_EXTENSIONS,
  ['application/pdf', 'pdf'],
  ['text/plain', 'txt'],
  ['application/zip', 'zip'],
  ['application/msword', 'doc'],
  [
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'docx',
  ],
  ['application/vnd.ms-excel', 'xls'],
  ['application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', 'xlsx'],
  ['application/vnd.ms-powerpoint', 'ppt'],
  [
    'application/vnd.openxmlformats-officedocument.presentationml.presentation',
    'pptx',
  ],
]);

const SAFE_FILE_NAME = /[^a-zA-Z0-9._ -]/g;

export function getAvatarExtension(contentType: string): string | null {
  return AVATAR_MIME_EXTENSIONS.get(contentType.toLowerCase()) ?? null;
}

export function getAttachmentExtension(contentType: string): string | null {
  return ATTACHMENT_MIME_EXTENSIONS.get(contentType.toLowerCase()) ?? null;
}

/**
 * Produce a display-safe file name. This is only for showing to users; the
 * storage key never uses it.
 */
export function sanitizeFileName(fileName: string): string {
  const baseName = fileName.split(/[\\/]/).pop() ?? '';
  const sanitized = baseName
    .replace(SAFE_FILE_NAME, '_')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 120);

  return sanitized || 'attachment';
}

export function buildAvatarKey(userId: string, contentType: string): string {
  const extension = getAvatarExtension(contentType);
  if (!extension) {
    throw new Error('Unsupported avatar content type');
  }

  return `avatars/${userId}-${Date.now()}.${extension}`;
}

export function buildDocumentKey(userId: string, contentType: string): string {
  const extension = getAttachmentExtension(contentType);
  if (!extension) {
    throw new Error('Unsupported document content type');
  }

  return `documents/${userId}/${randomUUID()}.${extension}`;
}

export function buildChatAttachmentKey(
  exchangeId: string,
  contentType: string,
): string {
  const extension = getAttachmentExtension(contentType);
  if (!extension) {
    throw new Error('Unsupported attachment content type');
  }

  return `exchange-chat/${exchangeId}/${randomUUID()}.${extension}`;
}

/**
 * Avatar keys are generated by the server as avatars/<userId>-<timestamp>.<ext>.
 * A user may only confirm a key that belongs to their own namespace.
 */
export function isOwnedAvatarKey(userId: string, key: string): boolean {
  const prefix = `avatars/${userId}-`;
  if (!key.startsWith(prefix)) return false;

  const remainder = key.slice(prefix.length);
  return /^\d+\.(?:jpg|jpeg|png|webp|gif|avif)$/.test(remainder);
}

/**
 * Chat attachments live under exchange-chat/<exchangeId>/. Restricting the
 * prefix stops a participant from requesting a signed URL for someone else's
 * object.
 */
export function isExchangeChatKey(exchangeId: string, key: string): boolean {
  const prefix = `exchange-chat/${exchangeId}/`;
  if (!key.startsWith(prefix)) return false;
  if (key.length > 512) return false;
  if (key.includes('..') || key.includes('\\')) return false;

  // Exactly one path segment below the exchange directory.
  return !key.slice(prefix.length).includes('/');
}
